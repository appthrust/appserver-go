// Command gen generates Go types and link-callable operations from callee-owned
// definition contracts or SDK-owned capability contracts. Run it from contract/<package>.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

type schema struct {
	Ref        string            `json:"$ref"`
	Type       string            `json:"type"`
	Properties map[string]schema `json:"properties"`
	Required   []string          `json:"required"`
}
type parameter struct {
	Ref      string `json:"$ref"`
	Name     string `json:"name"`
	In       string `json:"in"`
	Required bool   `json:"required"`
	Schema   schema `json:"schema"`
}
type requestBody struct {
	Ref     string `json:"$ref"`
	Content map[string]struct {
		Schema schema `json:"schema"`
	} `json:"content"`
}
type operation struct {
	ID          string      `json:"operationId"`
	Summary     string      `json:"summary"`
	Link        bool        `json:"x-appthrust-link"`
	ResultPath  string      `json:"x-appthrust-result-path"`
	Parameters  []parameter `json:"parameters"`
	RequestBody requestBody `json:"requestBody"`
}
type document struct {
	Definition string `json:"x-appthrust-definition"`
	Capability string `json:"x-appthrust-capability"`
	Servers    []struct {
		URL string `json:"url"`
	} `json:"servers"`
	Paths      map[string]map[string]json.RawMessage `json:"paths"`
	Components struct {
		Schemas       map[string]schema      `json:"schemas"`
		Parameters    map[string]parameter   `json:"parameters"`
		RequestBodies map[string]requestBody `json:"requestBodies"`
	} `json:"components"`
}

func main() {
	pkg := flag.String("package", "", "Go package name")
	source := flag.String("source", "", "OpenAPI path (default cmd/<package>-server/internal/api/openapi.json)")
	flag.Parse()
	if err := generate(*pkg, *source); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(pkg, source string) error {
	if !token.IsIdentifier(pkg) || token.Lookup(pkg).IsKeyword() {
		return fmt.Errorf("invalid Go package %q", pkg)
	}
	root, err := repoRoot()
	if err != nil {
		return err
	}
	if source == "" {
		source = filepath.Join(root, "cmd", pkg+"-server", "internal/api/openapi.json")
	}
	data, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	ops, err := emitOperations(pkg, data)
	if err != nil {
		return err
	}
	// Use the repository's pinned tool in platform-api/go.mod. An absolute
	// input path keeps generation independent of the tooling module's cwd.
	absoluteSource, err := filepath.Abs(source)
	if err != nil {
		return err
	}
	command := exec.Command("go", "tool", "oapi-codegen", "-generate", "types,skip-prune", "-package", pkg, absoluteSource)
	command.Dir = filepath.Join(root, "platform-api")
	var stderr bytes.Buffer
	command.Stderr = &stderr
	types, err := command.Output()
	if err != nil {
		return fmt.Errorf("oapi-codegen: %w: %s", err, stderr.String())
	}
	for _, file := range []struct {
		name string
		data []byte
	}{{"openapi.json", data}, {"types.gen.go", types}, {"ops.gen.go", ops}} {
		if err := os.WriteFile(file.name, file.data, 0644); err != nil {
			return err
		}
	}
	return nil
}

func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "platform-api/go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("repository root not found")
		}
		dir = parent
	}
}

func exportName(id string) string {
	var result strings.Builder
	upper := true
	for _, r := range id {
		if r == '-' || r == '_' {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		result.WriteRune(r)
	}
	return result.String()
}

func emitOperations(pkg string, data []byte) ([]byte, error) {
	var doc document
	if err := json.Unmarshal(data, &doc); err != nil {
		return nil, err
	}
	if (doc.Definition == "") == (doc.Capability == "") {
		return nil, fmt.Errorf("exactly one of x-appthrust-definition and x-appthrust-capability is required")
	}
	if len(doc.Servers) == 0 {
		return nil, fmt.Errorf("servers[0].url is required")
	}
	base := doc.Servers[0].URL
	if (base == "" && doc.Capability == "") || (base != "" && !strings.HasPrefix(base, "/")) || strings.HasPrefix(base, "//") || strings.ContainsAny(base, "?#{}") {
		return nil, fmt.Errorf("servers[0].url must be relative; only capability contracts may use an empty URL")
	}
	targetField, target := "Definition", doc.Definition
	if doc.Capability != "" {
		targetField, target = "Capability", doc.Capability
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by built-in app contract gen. DO NOT EDIT.\npackage %s\n\nimport (\n_ \"embed\"\n\"github.com/appthrust/appserver-go/appserver/link\"\n)\n\n//go:embed openapi.json\nvar Document []byte\n\n", pkg)
	if doc.Capability != "" {
		fmt.Fprintf(&out, "const Capability = %q\n\n", doc.Capability)
	}
	paths := make([]string, 0, len(doc.Paths))
	for path := range doc.Paths {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var names []string
	seen := make(map[string]bool)
	for _, path := range paths {
		item := doc.Paths[path]
		var shared []parameter
		if raw := item["parameters"]; raw != nil {
			if err := json.Unmarshal(raw, &shared); err != nil {
				return nil, err
			}
		}
		for _, method := range []string{"get", "post", "put", "patch", "delete", "head", "options"} {
			raw := item[method]
			if raw == nil {
				continue
			}
			var op operation
			if err := json.Unmarshal(raw, &op); err != nil {
				return nil, err
			}
			if !op.Link {
				continue
			}
			name := exportName(op.ID)
			if !token.IsIdentifier(name) || name == "Document" || name == "Operations" || (doc.Capability != "" && name == "Capability") || seen[name] {
				return nil, fmt.Errorf("invalid or duplicate operationId %q", op.ID)
			}
			seen[name] = true
			names = append(names, name)
			fmt.Fprintf(&out, "var %s = link.Operation{%s:%q, ID:%q, Method:%q, Base:%q, Path:%q, ResultPath:%q, Summary:%q, Params: []link.Param{\n", name, targetField, target, op.ID, strings.ToUpper(method), base, path, op.ResultPath, op.Summary)
			params := append(append([]parameter(nil), shared...), op.Parameters...)
			for index, param := range params {
				param, err := doc.resolveParam(param)
				if err != nil {
					return nil, err
				}
				// Operation parameters override a matching path-level parameter.
				overridden := false
				for _, later := range params[index+1:] {
					later, err = doc.resolveParam(later)
					if err != nil {
						return nil, err
					}
					if later.Name == param.Name && later.In == param.In {
						overridden = true
					}
				}
				if overridden {
					continue
				}
				s, err := doc.resolveSchema(param.Schema)
				if err != nil {
					return nil, err
				}
				fmt.Fprintf(&out, "{Name:%q, In:%q, Type:%q, Required:%t},\n", param.Name, param.In, s.Type, param.Required)
			}
			body := op.RequestBody
			if body.Ref != "" {
				var ok bool
				body, ok = doc.Components.RequestBodies[strings.TrimPrefix(body.Ref, "#/components/requestBodies/")]
				if !ok {
					return nil, fmt.Errorf("unresolved request body %q", op.RequestBody.Ref)
				}
			}
			if media, ok := body.Content["application/json"]; ok {
				s, err := doc.resolveSchema(media.Schema)
				if err != nil {
					return nil, err
				}
				fields := make([]string, 0, len(s.Properties))
				for field := range s.Properties {
					fields = append(fields, field)
				}
				sort.Strings(fields)
				for _, field := range fields {
					property, err := doc.resolveSchema(s.Properties[field])
					if err != nil {
						return nil, err
					}
					required := false
					for _, name := range s.Required {
						if field == name {
							required = true
						}
					}
					fmt.Fprintf(&out, "{Name:%q, In:\"body\", Type:%q, Required:%t},\n", field, property.Type, required)
				}
			}
			fmt.Fprintln(&out, "}}")
		}
	}
	fmt.Fprintf(&out, "\nvar Operations = []link.Operation{%s}\n", strings.Join(names, ","))
	return format.Source(out.Bytes())
}

func (d document) resolveSchema(s schema) (schema, error) {
	for depth := 0; s.Ref != ""; depth++ {
		if depth == 32 {
			return schema{}, fmt.Errorf("cyclic schema reference")
		}
		ref := s.Ref
		var ok bool
		s, ok = d.Components.Schemas[strings.TrimPrefix(ref, "#/components/schemas/")]
		if !ok {
			return schema{}, fmt.Errorf("unresolved schema %q", ref)
		}
	}
	return s, nil
}
func (d document) resolveParam(p parameter) (parameter, error) {
	if p.Ref == "" {
		return p, nil
	}
	resolved, ok := d.Components.Parameters[strings.TrimPrefix(p.Ref, "#/components/parameters/")]
	if !ok || resolved.Ref != "" {
		return parameter{}, fmt.Errorf("unresolved parameter %q", p.Ref)
	}
	return resolved, nil
}
